#pragma once

#include <NF/ECS/Entity.hpp>
#include <NF/ECS/ECS.hpp>

#include <functional>
#include <vector>
#include <unordered_map>
#include <utility>

namespace nf::ecs {

/// Records ECS structural mutations during query iteration or system runs,
/// and replays them atomically onto the World at a safe synchronization point.
class EntityCommandBuffer {
public:
    static constexpr u32 kPlaceholderFlag = 0x80000000u;

    EntityCommandBuffer() = default;
    ~EntityCommandBuffer() = default;

    // Non-copyable, movable
    EntityCommandBuffer(const EntityCommandBuffer&) = delete;
    EntityCommandBuffer& operator=(const EntityCommandBuffer&) = delete;
    EntityCommandBuffer(EntityCommandBuffer&&) noexcept = default;
    EntityCommandBuffer& operator=(EntityCommandBuffer&&) noexcept = default;

    /// Checks if an entity is a deferred placeholder generated by this buffer.
    static bool is_placeholder(Entity e) {
        return (e.id & kPlaceholderFlag) != 0;
    }

    /// Records the creation of a new entity. Returns a deferred placeholder entity
    /// that can immediately be passed to add_component, set_component, or destroy_entity
    /// within this buffer. During playback(), real entities are created and remapped.
    Entity create_entity();

    /// Records the destruction of an entity.
    void destroy_entity(Entity entity);

    /// Records adding a component to an entity.
    template<typename T>
    void add_component(Entity entity, T component) {
        m_commands.push_back([entity, comp = std::move(component)](
            World& world, const std::unordered_map<Entity, Entity>& remap) mutable {
            Entity target = resolve_entity(entity, remap);
            if (world.is_alive(target)) {
                world.add<T>(target, std::move(comp));
            }
        });
    }

    /// Records setting/replacing a component on an entity.
    template<typename T>
    void set_component(Entity entity, T component) {
        m_commands.push_back([entity, comp = std::move(component)](
            World& world, const std::unordered_map<Entity, Entity>& remap) mutable {
            Entity target = resolve_entity(entity, remap);
            if (world.is_alive(target)) {
                if (auto* existing = world.get<T>(target)) {
                    *existing = std::move(comp);
                } else {
                    world.add<T>(target, std::move(comp));
                }
            }
        });
    }

    /// Records removing a component from an entity.
    template<typename T>
    void remove_component(Entity entity) {
        m_commands.push_back([entity](
            World& world, const std::unordered_map<Entity, Entity>& remap) {
            Entity target = resolve_entity(entity, remap);
            if (world.is_alive(target)) {
                world.remove<T>(target);
            }
        });
    }

    /// Records an arbitrary deferred callback to be invoked during playback.
    void add_action(std::function<void(World&)> action);

    /// Plays back all recorded commands in sequence onto the target World.
    /// Resets the buffer after playback.
    void playback(World& world);

    /// Discards all recorded commands without executing them.
    void clear();

    /// Returns whether any commands have been recorded.
    bool empty() const { return m_commands.empty() && m_placeholder_count == 0; }

    /// Returns the number of recorded operations.
    size_t command_count() const { return m_commands.size(); }

private:
    static Entity resolve_entity(Entity e, const std::unordered_map<Entity, Entity>& remap) {
        if (!is_placeholder(e)) return e;
        auto it = remap.find(e);
        return it != remap.end() ? it->second : kInvalidEntity;
    }

    using CommandFn = std::function<void(World&, const std::unordered_map<Entity, Entity>&)>;
    std::vector<CommandFn> m_commands;
    u32 m_placeholder_count = 0;
};

} // namespace nf::ecs
